import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier, plot_tree
from sklearn.metrics import classification_report, accuracy_score
from sklearn.preprocessing import LabelEncoder

# Reload data to ensure a fresh, unmutated copy
df = pd.read_csv('/content/extracted_data/starbucks_drinkMenu_expanded.csv')
df.columns = df.columns.str.strip()

# 1. Clean numerical values stored as strings
def clean_percentage(val):
    if isinstance(val, str):
        return float(val.replace('%', '').strip())
    return float(val)

def clean_numeric(val):
    if isinstance(val, str):
        val = val.strip()
        if val == '' or val.lower() == 'varies':
            return np.nan
        # Handle typos like '3 2' by converting to '3.2' or picking the first one
        # In this dataset, '3 2' is a known typo for '3.2'
        if ' ' in val:
            val = val.replace(' ', '.')
        try:
            return float(val)
        except ValueError:
            return np.nan
    try:
        return float(val)
    except:
        return np.nan

# Clean features
df['Total Fat (g)'] = df['Total Fat (g)'].apply(clean_numeric)
df['Vitamin A (% DV)'] = df['Vitamin A (% DV)'].apply(clean_percentage)
df['Vitamin C (% DV)'] = df['Vitamin C (% DV)'].apply(clean_percentage)
df['Calcium (% DV)'] = df['Calcium (% DV)'].apply(clean_percentage)
df['Iron (% DV)'] = df['Iron (% DV)'].apply(clean_percentage)
df['Caffeine (mg)'] = df['Caffeine (mg)'].apply(clean_numeric)

# Handle missing values by filling or dropping
df = df.dropna()

# 2. Select numerical features for predicting the Beverage Category
features = ['Calories', 'Total Fat (g)', 'Trans Fat (g)', 'Saturated Fat (g)',
            'Sodium (mg)', 'Total Carbohydrates (g)', 'Cholesterol (mg)',
            'Dietary Fibre (g)', 'Sugars (g)', 'Protein (g)', 'Vitamin A (% DV)',
            'Vitamin C (% DV)', 'Calcium (% DV)', 'Iron (% DV)', 'Caffeine (mg)']

X = df[features]
y = df['Beverage_category']

# Encode target labels
le = LabelEncoder()
y_encoded = le.fit_transform(y)

# 3. Train-Test Split (using stratify if counts permit, otherwise regular split)
try:
    X_train, X_test, y_train, y_test = train_test_split(X, y_encoded, test_size=0.25, random_state=42, stratify=y_encoded)
except ValueError:
    # Fallback in case of rare classes making stratify impossible
    X_train, X_test, y_train, y_test = train_test_split(X, y_encoded, test_size=0.25, random_state=42)

# 4. Train Decision Tree Classifier
clf = DecisionTreeClassifier(max_depth=5, random_state=42)
clf.fit(X_train, y_train)

# 5. Predict and Evaluate
y_pred = clf.predict(X_test)
accuracy = accuracy_score(y_test, y_pred)

print(f"Decision Tree Classification Accuracy: {accuracy:.2%}\n")
print("--- Classification Report ---")
print(classification_report(y_test, y_pred, target_names=le.classes_))

# 6. Draw the Pie Chart of Beverage Categories
plt.figure(figsize=(10, 8))
category_counts = df['Beverage_category'].value_counts()
plt.pie(category_counts, labels=category_counts.index, autopct='%1.1f%%', startangle=140, colors=sns.color_palette('pastel'))
plt.title('Distribution of Starbucks Beverage Categories (Pie Chart)')
plt.tight_layout()
plt.show()

import joblib

# Save the model and label encoder
model_filename = 'starbucks_decision_tree_model.joblib'
encoder_filename = 'label_encoder.joblib'

joblib.dump(clf, model_filename)
joblib.dump(le, encoder_filename)

print(f"Model successfully saved as: {model_filename}")
